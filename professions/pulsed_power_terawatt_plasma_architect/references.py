from dataclasses import dataclass, field
import math
from typing import Dict, List


# Physical Constants
MU_0 = 4.0 * math.pi * 1e-7          # Vacuum magnetic permeability (H/m)
PASCAL_PER_MBAR = 1.0e11            # 1 Mbar = 100 GPa = 1.0e11 Pa
ELEMENTARY_CHARGE_C = 1.602176634e-19 # Elementary charge (C)

# Quantitative Threshold Boundaries
MIN_PEAK_CURRENT_MA = 20.0
MAX_RISE_TIME_NS = 100.0
MIN_PEAK_POWER_TW = 80.0
MIN_MAGNETIC_PRESSURE_MBAR = 10.0
MIN_PRESEED_BFIELD_TESLA = 10.0
MIN_LASER_PREHEAT_ENERGY_KJ = 2.0
MIN_CONVERGENCE_RATIO = 15.0
MAX_CONVERGENCE_RATIO = 35.0
MAX_MRT_AMPLITUDE_RATIO = 0.15
MAX_SWITCH_JITTER_NS = 2.0
MIN_ENERGY_DENSITY_KJ_M3 = 50.0
MIN_STAGNATION_TEMP_KEV = 3.0
MIN_NEUTRON_YIELD = 1.0e14


def calculate_magnetic_pressure_mbar(
    current_amperes: float,
    radius_meters: float,
) -> float:
    """Calculate peak magnetic pressure P_mag = (mu_0 * I^2) / (8 * pi^2 * r^2) in Mbar."""
    if radius_meters <= 0.0:
        raise ValueError("Liner radius must be positive.")
    if current_amperes <= 0.0:
        raise ValueError("Discharge current must be positive.")
    
    pressure_pascals = (MU_0 * (current_amperes ** 2)) / (8.0 * (math.pi ** 2) * (radius_meters ** 2))
    return pressure_pascals / PASCAL_PER_MBAR


def calculate_convergence_ratio(
    initial_radius_m: float,
    stagnation_radius_m: float,
) -> float:
    """Calculate radial convergence ratio CR = r_0 / r_stag."""
    if stagnation_radius_m <= 0.0 or initial_radius_m <= 0.0:
        raise ValueError("Radii must be strictly positive.")
    if initial_radius_m < stagnation_radius_m:
        raise ValueError("Initial radius must be >= stagnation radius.")
    return initial_radius_m / stagnation_radius_m


def calculate_stagnation_axial_field_tesla(
    b0_tesla: float,
    convergence_ratio: float,
    flux_loss_fraction: float = 0.15,
) -> float:
    """Calculate compressed axial magnetic field B_stag = B_0 * CR^2 * (1 - f_loss)."""
    if b0_tesla <= 0.0:
        raise ValueError("Initial axial magnetic field must be positive.")
    if convergence_ratio < 1.0:
        raise ValueError("Convergence ratio must be >= 1.0.")
    if not (0.0 <= flux_loss_fraction < 1.0):
        raise ValueError("Flux loss fraction must be in [0.0, 1.0).")
    return b0_tesla * (convergence_ratio ** 2) * (1.0 - flux_loss_fraction)


def calculate_water_breakdown_field_mv_cm(
    effective_time_us: float,
    area_cm2: float,
) -> float:
    """Calculate Martin empirical breakdown electric field in deionized water (MV/cm)."""
    if effective_time_us <= 0.0 or area_cm2 <= 0.0:
        raise ValueError("Effective pulse time and electrode area must be positive.")
    return 0.23 * (effective_time_us ** (-1.0 / 3.0)) * (area_cm2 ** (-0.10))


def calculate_peak_electrical_power_tw(
    voltage_megavolts: float,
    current_megaamperes: float,
) -> float:
    """Calculate peak electrical power P = V * I in Terawatts (TW)."""
    if voltage_megavolts < 0.0 or current_megaamperes < 0.0:
        raise ValueError("Voltage and current must be non-negative.")
    return voltage_megavolts * current_megaamperes


@dataclass
class PulsedPowerParameters:
    """Quantitative parameters defining pulsed power Z-pinch plasma drive state."""
    peak_current_ma: float
    rise_time_ns: float
    peak_power_tw: float
    magnetic_pressure_mbar: float
    preseed_bfield_tesla: float
    laser_preheat_energy_kj: float
    convergence_ratio: float
    mrt_amplitude_ratio: float
    switch_jitter_ns: float
    energy_density_kj_m3: float
    stagnation_temperature_kev: float
    neutron_yield: float


@dataclass
class PulsedPowerValidationResult:
    """Validation report generated by Dr. Thaddeus Vance's pulsed power invariants."""
    is_valid: bool
    violations: List[str] = field(default_factory=list)
    score: float = 100.0
    metrics: Dict[str, float] = field(default_factory=dict)


def validate_pulsed_power_parameters(params: PulsedPowerParameters) -> PulsedPowerValidationResult:
    """Validate pulsed power high-energy-density parameters against strict physical invariants."""
    violations: List[str] = []
    deductions: float = 0.0

    # 1. Peak discharge current
    if params.peak_current_ma < MIN_PEAK_CURRENT_MA:
        violations.append(
            f"Peak current sub-critical: {params.peak_current_ma:.1f} MA < {MIN_PEAK_CURRENT_MA:.1f} MA. "
            "Insufficient drive to generate multi-megabar magnetic implosion."
        )
        deductions += 25.0

    # 2. Current rise time
    if params.rise_time_ns > MAX_RISE_TIME_NS:
        violations.append(
            f"Current rise time too slow: {params.rise_time_ns:.1f} ns > {MAX_RISE_TIME_NS:.1f} ns. "
            "Magneto-Rayleigh-Taylor instability bubbles will disrupt liner before stagnation."
        )
        deductions += 20.0

    # 3. Peak electrical power
    if params.peak_power_tw < MIN_PEAK_POWER_TW:
        violations.append(
            f"Peak power below terawatt threshold: {params.peak_power_tw:.1f} TW < {MIN_PEAK_POWER_TW:.1f} TW."
        )
        deductions += 15.0

    # 4. Magnetic implosion pressure
    if params.magnetic_pressure_mbar < MIN_MAGNETIC_PRESSURE_MBAR:
        violations.append(
            f"Magnetic drive pressure sub-megabar: {params.magnetic_pressure_mbar:.2f} Mbar < {MIN_MAGNETIC_PRESSURE_MBAR:.1f} Mbar."
        )
        deductions += 15.0

    # 5. Pre-seeded axial magnetic field (MagLIF)
    if params.preseed_bfield_tesla < MIN_PRESEED_BFIELD_TESLA:
        violations.append(
            f"Pre-seeded axial B-field too weak: {params.preseed_bfield_tesla:.1f} T < {MIN_PRESEED_BFIELD_TESLA:.1f} T. "
            "Electron thermal conduction suppression will fail."
        )
        deductions += 15.0

    # 6. Laser pre-heat energy
    if params.laser_preheat_energy_kj < MIN_LASER_PREHEAT_ENERGY_KJ:
        violations.append(
            f"Laser pre-heat energy insufficient: {params.laser_preheat_energy_kj:.2f} kJ < {MIN_LASER_PREHEAT_ENERGY_KJ:.2f} kJ."
        )
        deductions += 10.0

    # 7. Convergence ratio envelope
    if not (MIN_CONVERGENCE_RATIO <= params.convergence_ratio <= MAX_CONVERGENCE_RATIO):
        violations.append(
            f"Convergence ratio out of stable MagLIF window: {params.convergence_ratio:.1f} "
            f"not in [{MIN_CONVERGENCE_RATIO:.1f}, {MAX_CONVERGENCE_RATIO:.1f}]."
        )
        deductions += 10.0

    # 8. MRT instability amplitude
    if params.mrt_amplitude_ratio > MAX_MRT_AMPLITUDE_RATIO:
        violations.append(
            f"MRT instability amplitude excessive: {params.mrt_amplitude_ratio * 100:.1f}% > {MAX_MRT_AMPLITUDE_RATIO * 100:.1f}%. "
            "Liner wall breakup imminent."
        )
        deductions += 10.0

    # 9. Switch jitter synchronization
    if params.switch_jitter_ns > MAX_SWITCH_JITTER_NS:
        violations.append(
            f"Switch trigger jitter excessive: {params.switch_jitter_ns:.2f} ns > {MAX_SWITCH_JITTER_NS:.2f} ns. "
            "Asymmetric pulse arrival at convolute."
        )
        deductions += 10.0

    # 10. Transmission line energy density
    if params.energy_density_kj_m3 < MIN_ENERGY_DENSITY_KJ_M3:
        violations.append(
            f"Pulse forming line energy density too low: {params.energy_density_kj_m3:.1f} kJ/m^3 < {MIN_ENERGY_DENSITY_KJ_M3:.1f} kJ/m^3."
        )
        deductions += 5.0

    # 11. Thermonuclear stagnation temperature
    if params.stagnation_temperature_kev < MIN_STAGNATION_TEMP_KEV:
        violations.append(
            f"Stagnation temperature below fusion threshold: {params.stagnation_temperature_kev:.2f} keV < {MIN_STAGNATION_TEMP_KEV:.2f} keV."
        )
        deductions += 5.0

    # 12. Thermonuclear neutron yield
    if params.neutron_yield < MIN_NEUTRON_YIELD:
        violations.append(
            f"Neutron yield below thermonuclear benchmark: {params.neutron_yield:.2e} < {MIN_NEUTRON_YIELD:.2e}."
        )
        deductions += 5.0

    final_score = max(0.0, 100.0 - deductions)
    is_valid = len(violations) == 0

    metrics = {
        "peak_current_ma": params.peak_current_ma,
        "rise_time_ns": params.rise_time_ns,
        "peak_power_tw": params.peak_power_tw,
        "magnetic_pressure_mbar": params.magnetic_pressure_mbar,
        "preseed_bfield_tesla": params.preseed_bfield_tesla,
        "laser_preheat_energy_kj": params.laser_preheat_energy_kj,
        "convergence_ratio": params.convergence_ratio,
        "mrt_amplitude_ratio": params.mrt_amplitude_ratio,
        "switch_jitter_ns": params.switch_jitter_ns,
        "energy_density_kj_m3": params.energy_density_kj_m3,
        "stagnation_temperature_kev": params.stagnation_temperature_kev,
        "neutron_yield": params.neutron_yield,
    }

    return PulsedPowerValidationResult(
        is_valid=is_valid,
        violations=violations,
        score=final_score,
        metrics=metrics,
    )
